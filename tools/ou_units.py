# 和人地（北海道的市町村名）
WAJINCHI = {'函館市', '北斗市', '七飯町', '知内町', '木古内町', '福島町', '松前町', '上ノ国町', '江差町', '厚沢部町', '乙部町'}


def unit_of(props, pref):
    """市区町村 → 分区键（不在奥羽 / 和人地的返回 None）"""
    name = props['name']
    if pref == 1:
        return '和人地' if name in WAJINCHI else None
    if props.get('province') not in ('陸奥国', '出羽国'):
        return None
    if name in MUNI:
        return MUNI[name]
    od = props.get('old_districts') or []
    whole = [n for n, part in od if not part]
    if not whole:
        raise SystemExit(f'{name} 没有整体属于的旧郡：在 ou_units.MUNI 里指定分区')
    for k, u in UNITS.items():
        if whole[0] in u[5]:
            if u[4] != props['province']:
                raise SystemExit(f'{name}：旧郡 {whole[0]} 属于 {k}（{u[4]}），与市町村的旧国 {props["province"]} 不一致')
            return k
    raise SystemExit(f'{name}：旧郡 {whole[0]} 不在任何分区里')
